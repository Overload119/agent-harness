import { rm } from "node:fs/promises";
import path from "node:path";
import { listSkillDirectories, writeSkillDirectory } from "../src/setup/skills";
import { createTemplateVariables } from "../src/setup/constants";
import { renderTemplateFile } from "../src/setup/template";

// This selection is exported separately for skills-only installation.
export const PORTABLE_SKILLS = [
  "adhd",
  "be-ambitious",
  "completion-focus",
  "handoff",
  "plain-communication",
  "r-plan",
  "restate",
  "side-chats",
  "sync-harness",
  "thread-routing",
  "unsure",
  "user-scenarios",
  "working-artifacts",
  "weekly-goals-brief",
] as const;

const rootDir = path.resolve(import.meta.dir, "..");

export async function exportHarnessSkills(outputDir = path.join(rootDir, "dist", "plugin-skills")): Promise<void> {
  const variables = await createTemplateVariables(rootDir);
  await rm(outputDir, { recursive: true, force: true });
  for (const sourceDir of await listSkillDirectories(path.join(rootDir, "skills"))) {
    const rendered = await renderTemplateFile(path.join(sourceDir, "SKILL.md.liquid"), variables);
    const metadata = Bun.YAML.parse(rendered.match(/^---\n([\s\S]*?)\n---/)![1]) as { name: string };
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(metadata.name)) throw new Error(`Invalid skill name in ${sourceDir}`);
    const target = path.join(outputDir, metadata.name);
    await writeSkillDirectory(sourceDir, target, variables);
    if (metadata.name === "ah-mermaid") {
      const bundle = await Bun.build({
        entrypoints: [path.join(sourceDir, "scripts", "render-mermaid.ts")],
        target: "bun", format: "esm", minify: true,
      });
      if (!bundle.success) throw new Error(`Mermaid bundle failed: ${bundle.logs.join("\n")}`);
      await Bun.write(path.join(target, "scripts", "render-mermaid.ts"), await bundle.outputs[0].text());
    }
  }
}

export async function exportStandingInstructions(): Promise<void> {
  const instructions = await Bun.file(path.join(rootDir, "instructions", "AGENTS.md")).text();
  if (instructions.length > 4096) throw new Error("Standing instructions exceed BB's 4096-character limit.");
  await Bun.write(path.join(rootDir, "src", "plugin", "instructions.ts"),
    `// Generated by scripts/export-skills.ts; edit instructions/AGENTS.md.\nexport const STANDING_INSTRUCTIONS = ${JSON.stringify(instructions)};\n`);
}

export async function exportPortableSkills(
  outputDir = path.join(rootDir, "dist", "skills"),
): Promise<void> {
  // This directory contains generated exports only; remove obsolete skills too.
  await rm(outputDir, { recursive: true, force: true });
  for (const name of PORTABLE_SKILLS) {
    await writeSkillDirectory(
      path.join(rootDir, "skills", `ah-${name}`),
      path.join(outputDir, name),
      {},
    );
  }
}

if (import.meta.main) {
  await exportHarnessSkills();
  await exportPortableSkills();
  await exportStandingInstructions();
  console.log(`Exported ${PORTABLE_SKILLS.length} portable skills to dist/skills`);
}
